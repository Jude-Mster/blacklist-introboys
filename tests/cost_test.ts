import { member, settings, call, pts, ok, done, enter } from './h.ts';
import tour from '../base44/functions/tournamentAction/entry.ts';
await settings();
const L = await member('Juts', 100000, 'leader'), A = await member('A', 50000);
let r = await call(tour, L, { action: 'create', predict_minutes: 0, title: 'Price Cup', prizes: [{ kind: 'points', points: 100 }], costs: { entry: 200, skill: 3000, weaponTry: 50, pet: 7, mountLevel: 999, mountReset: -5 } });
ok(r.ok, 'create with prices');
let s = await call(tour, A, { action: 'state' });
ok(s.costs.entry === 200 && s.costs.skill === 3000 && s.costs.pet === 7 && s.costs.mountReset === 2500, 'prices saved, bad one falls back: ' + JSON.stringify(s.costs));
ok(s.tournament.costs.weaponTry === 50, 'tournament carries its prices');
ok(s.costs.join === 200 && s.costs.roll === 200, 'an old entry price sets the join and random stat prices');
r = await enter(tour, A, 2, 200);
ok(r.ok && await pts(A) === 50000 - 400, 'join + 1 random stat charged at the leader price');
r = await call(tour, L, { action: 'edit', costs: { ...s.costs, skill: 1234 } });
ok(r.ok !== false, 'leader edits a price');
r = await call(tour, A, { action: 'buy', item: 'skill', price: 3000 });
ok(r.status === 400 && /price just changed to 1,234/.test(r.error), 'stale price refused: ' + r.error);
ok(await pts(A) === 49600, 'nothing charged on a stale price');
r = await call(tour, A, { action: 'buy', item: 'skill', price: 1234 });
ok(r.ok && await pts(A) === 49600 - 1234, 'new price charged');
r = await call(tour, A, { action: 'buy', item: 'weapon' });
ok(r.ok && await pts(A) === 49600 - 1234 - 50, 'no price sent still uses the tournament price');
done();