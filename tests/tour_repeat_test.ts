import { advance, member, settings, call, ok, done, E } from './h.ts';
import tour from '../base44/functions/tournamentAction/entry.ts';
await settings();
const L = await member('Juts', 100000, 'leader');
const ms = []; for (let i = 0; i < 3; i++) ms.push(await member('F' + i, 50000));
const start = Date.now() + 30 * 60000;
let r = await call(tour, L, { action: 'create', predict_minutes: 0, title: 'Weekly Cup', repeat: 'weekly', prizes: [{ kind: 'points', points: 1000 }] });
ok(r.status === 400 && /start time/.test(r.error), 'repeat needs a start time');
r = await call(tour, L, { action: 'create', predict_minutes: 0, title: 'Weekly Cup', repeat: 'weekly', starts_at: new Date(start).toISOString(), prizes: [{ kind: 'points', points: 1000 }] });
ok(r.ok, 'create weekly');
for (const m of ms) await call(tour, m, { action: 'buy', item: 'entry' });
let s = await call(tour, ms[0], { action: 'state' });
ok(s.tournament.repeat === 'weekly', 'repeat shown');
const chat = async () => (await E.ChatMessage.filter({}, {})).items.map((x) => x.text);
ok(!(await chat()).some((x) => /starts in/.test(x)), 'no reminder yet');
advance(21 * 60000);
s = await call(tour, ms[0], { action: 'state' });
ok((await chat()).some((x) => /starts in 9 minutes/.test(x)), 'reminder posted: ' + (await chat()).find((x) => /starts in/.test(x)));
s = await call(tour, ms[0], { action: 'state' });
ok((await chat()).filter((x) => /starts in/.test(x)).length === 1, 'reminder only once');
advance(10 * 60000);
s = await call(tour, ms[0], { action: 'state' });
ok(s.tournament.status === 'running', 'started');
ok((await chat()).some((x) => /has started/.test(x)), 'start posted');
advance(3 * 3600000);
s = await call(tour, ms[0], { action: 'state' });
ok(s.tournament && s.tournament.status === 'signup' && s.tournament.title === 'Weekly Cup', 'next one opened by itself');
ok(Date.parse(s.tournament.starts_at) === start + 7 * 24 * 3600000, 'a week after the last start');
ok(s.tournament.prizes[0].points === 1000 && s.tournament.repeat === 'weekly', 'same prizes, still weekly');
const all = (await E.Tournament.filter({}, {})).items;
ok(all.length === 2 && all.find((x) => x.status === 'done').next_id, 'done one points to the next');
// leader cancels the repeat: no next one
r = await call(tour, L, { action: 'cancel' });
s = await call(tour, ms[0], { action: 'state' });
ok(r.ok && s.tournament === null, 'leader cancel stops the repeat');
// 0 sign-ups on a daily one: cancelled, next one still opens
r = await call(tour, L, { action: 'create', predict_minutes: 0, title: 'Daily', repeat: 'daily', starts_at: new Date(Date.now() + 120000).toISOString() });
advance(130000);
s = await call(tour, ms[0], { action: 'state' });
ok(s.tournament && s.tournament.title === 'Daily' && s.tournament.status === 'signup', 'empty daily one cancelled and the next opened');
done();